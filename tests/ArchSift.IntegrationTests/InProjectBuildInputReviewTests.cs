using System.Xml.Linq;
using System.Text.Json;
using System.IO.Compression;
using ArchSift.Contracts;
using ArchSift.Core;
using ArchSift.InProject.Runtime;

namespace ArchSift.IntegrationTests;

public sealed class InProjectBuildInputReviewTests
{
    [Fact]
    public void RazorBuildTimeAnalyzersAreLimitedToTheSelectedSdkAndKnownFiles()
    {
        var sdk = Path.Combine(Path.GetTempPath(), "archsift-sdk-probe", "sdk", "10.0.303");
        var compiler = Path.Combine(sdk, "Roslyn", "bincore", "csc.dll");
        var folder = Path.Combine(sdk, "Sdks", "Microsoft.NET.Sdk.Razor", "source-generators");
        Assert.True(InProjectCompilerCaptures.ReviewedRazorBuildAnalyzer(compiler,
            Path.Combine(folder, "Microsoft.CodeAnalysis.Razor.Compiler.dll")));
        Assert.False(InProjectCompilerCaptures.ReviewedRazorBuildAnalyzer(compiler,
            Path.Combine(folder, "UnknownGenerator.dll")));
        Assert.False(InProjectCompilerCaptures.ReviewedRazorBuildAnalyzer(compiler,
            Path.Combine(Path.GetTempPath(), "other-sdk", "Microsoft.CodeAnalysis.Razor.Compiler.dll")));
    }

    [Fact]
    public void BundledReferenceAnalyzerMustMatchTheLockedArchiveBytes()
    {
        var root = Path.Combine(Path.GetTempPath(), "archsift-reference-review-" + Guid.NewGuid().ToString("N"));
        var install = Path.Combine(root, "install");
        var cache = Path.Combine(root, "cache");
        const string relative = "microsoft.netcore.app.ref/8.0.30/analyzers/dotnet/cs/ReferenceGenerator.dll";
        var analyzer = Path.Combine(cache, relative.Replace('/', Path.DirectorySeparatorChar));
        try
        {
            Directory.CreateDirectory(Path.Combine(install, "offline"));
            Directory.CreateDirectory(Path.GetDirectoryName(analyzer)!);
            File.WriteAllText(analyzer, "locked-analyzer");
            var archive = Path.Combine(install, "offline", "microsoft.netcore.app.ref.8.0.30.nupkg");
            using (var zip = ZipFile.Open(archive, ZipArchiveMode.Create))
            using (var entry = zip.CreateEntry("analyzers/dotnet/cs/ReferenceGenerator.dll").Open())
            using (var writer = new StreamWriter(entry)) writer.Write("locked-analyzer");
            Assert.True(InProjectBundledReferenceInputs.AllowsAnalyzer(install, cache, analyzer,
                LocalPackage.HashFile(analyzer)));
            File.WriteAllText(analyzer, "changed-analyzer");
            Assert.False(InProjectBundledReferenceInputs.AllowsAnalyzer(install, cache, analyzer,
                LocalPackage.HashFile(analyzer)));
        }
        finally
        {
            if (Directory.Exists(root) && PathSafety.IsUnder(root, Path.GetTempPath()))
                Directory.Delete(root, recursive: true);
        }
    }

    [Fact]
    public void PackageReviewPinsExecutableInputsAndGeneratedSourceNames()
    {
        var root = Path.Combine(Path.GetTempPath(), "archsift-package-review-" + Guid.NewGuid().ToString("N"));
        var packagePath = Path.Combine(root, "feed", "sample", "1.0.0", "build", "sample.targets");
        var reviewPath = Path.Combine(root, "build-input-review.json");
        try
        {
            Directory.CreateDirectory(Path.GetDirectoryName(packagePath)!);
            File.WriteAllText(packagePath, "<Project />");
            var hash = LocalPackage.HashFile(packagePath);
            File.WriteAllText(reviewPath, JsonSerializer.Serialize(new InProjectPackageReviewFile(1,
                "ArchSift.InProject", [new("sample/1.0.0/build/sample.targets", hash)],
                ["XunitAutoGeneratedEntryPoint.cs"]), JsonContract.Options));
            var review = InProjectPackageReview.Load(reviewPath)!;
            review.VerifyFeed(Path.Combine(root, "feed"));
            review.VerifyAsset(Path.Combine(root, "feed"), "Sample/1.0.0", "build/sample.targets");
            Assert.True(review.AllowsGeneratedSource("tests/Sample/obj/Debug/net10.0/XunitAutoGeneratedEntryPoint.cs"));
            Assert.False(review.AllowsGeneratedSource("tests/Sample/obj/Debug/net10.0/Unknown.cs"));
            Assert.Throws<ConfigurationException>(() => review.VerifyAsset(Path.Combine(root, "feed"),
                "Sample/1.0.0", "build/unknown.targets"));
            File.WriteAllText(packagePath, "<Project><Target Name=\"Changed\" /></Project>");
            Assert.Throws<ConfigurationException>(() => review.VerifyFeed(Path.Combine(root, "feed")));
        }
        finally
        {
            if (Directory.Exists(root) && PathSafety.IsUnder(root, Path.GetTempPath()))
                Directory.Delete(root, recursive: true);
        }
    }

    [Fact]
    public void ReviewedIfxPropertyConditionsAreAccepted()
    {
        const string xml = """
            <Project>
              <PropertyGroup>
                <NoWarn>$(NoWarn);CS1591</NoWarn>
                <WarningsAsErrors>$(WarningsAsErrors);NU1903</WarningsAsErrors>
                <RepositoryRoot>$(MSBuildThisFileDirectory)</RepositoryRoot>
                <ContinuousIntegrationBuild Condition="'$(CI)' == 'true'">true</ContinuousIntegrationBuild>
              </PropertyGroup>
              <PropertyGroup Condition="$(MSBuildProjectName.EndsWith('.Tests')) Or $(MSBuildProjectName.EndsWith('Tests.Common'))">
                <IsTestProject Condition="$(MSBuildProjectName.EndsWith('.Tests'))">true</IsTestProject>
              </PropertyGroup>
            </Project>
            """;

        InProjectBuildInputReview.Validate(XDocument.Parse(xml), "Directory.Build.props");
    }

    [Theory]
    [InlineData("<PropertyGroup Condition=\"Exists('..\\\\external.props')\"><NoWarn>CS1591</NoWarn></PropertyGroup>")]
    [InlineData("<PropertyGroup><Out>$(UnknownEnvironmentKey)</Out></PropertyGroup>")]
    [InlineData("<PropertyGroup Condition=\"'$(OtherEnvironmentKey)' == 'yes'\"><NoWarn>CS1591</NoWarn></PropertyGroup>")]
    [InlineData("<ItemGroup><Compile Include=\"$(NoWarn)\" /></ItemGroup>")]
    [InlineData("<PropertyGroup><RepositoryRoot>$(MSBuildThisFileDirectory)../../</RepositoryRoot></PropertyGroup>")]
    public void UnknownConditionalOrPropertyInputIsRejected(string innerXml)
    {
        Assert.Throws<ConfigurationException>(() => InProjectBuildInputReview.Validate(
            XDocument.Parse("<Project>" + innerXml + "</Project>"), "Directory.Build.props"));
    }
}
